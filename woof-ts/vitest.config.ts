import { defineConfig } from 'vitest/config';

// Таймауты щедрые намеренно: тесты гоняют НАСТОЯЩУЮ симуляцию игры (одно решение
// агента = цикл мировых действий) и настоящий env-сервер upstream за бриджем,
// а не моки. Быстрый тест ценой пропуска проверки — плохая сделка.
//
// Параллелизм выключен: машина с 2 ГБ RAM, а каждый мир (in-process Sim или
// процесс env_server) — это вся симуляция целиком. Параллельные прогоны дают
// OOM-kill, который выглядит как «тесты упали», хотя код цел.
export default defineConfig({
  // .ts ДО .js — и это не косметика.
  //
  // Дефолт Vite: ['.mjs', '.js', '.mts', '.ts', ...] — то есть .js РАНЬШЕ .ts.
  // Дефолт esbuild: ['.tsx', '.ts', '.jsx', '.js', ...] — то есть .ts РАНЬШЕ .js.
  // Значит если в дереве игры рядом с исходниками лежит собранный вывод
  // (src/sim/obs.ts И src/sim/obs.js), то `npm run build` берёт исходник,
  // а vitest — собранный файл. Симптом: сборка зелёная, тесты красные,
  // в дереве игры вне корня проекта — «ReferenceError: exports is not defined
  // in ES module scope» (игра объявляет "type": "module", а собранный .js — CJS).
  // Наши импорты игры без расширения ('../game/src/sim/obs'), поэтому порядок
  // резолвера решает, ОТКУДА берутся факты. Факты обязаны браться из исходников
  // upstream, а не из чьей-то сборки — проверяется также tools/verify_facts.ts.
  // Проверено репродукцией: грязное дерево + дефолт → грузится .js;
  // грязное дерево + этот список → грузится .ts; чистое дерево → .ts.
  resolve: {
    extensions: ['.mts', '.ts', '.tsx', '.mjs', '.js', '.jsx', '.json'],
  },
  test: {
    include: ['tests/**/*.test.ts'],
    testTimeout: 180_000,
    hookTimeout: 120_000,
    fileParallelism: false,
    maxWorkers: 1,
    minWorkers: 1,
  },
});
